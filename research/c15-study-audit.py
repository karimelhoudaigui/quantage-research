"""Hand-specified SYNTHETIC SOFTWARE FIXTURES, never LLM performance.

Command: python3 research/c15-study-audit.py --output NEW_DIRECTORY
"""
import argparse
import copy
import json
import math
from pathlib import Path
import sys

sys.path.insert(0, str(Path.cwd()))
from quantage.repair_model import parse_model
from quantage.repair_study import feedback, score, choose_direct, choose_revision
from quantage.repair_feedback import SCHEMA_MESSAGE, validate_feedback


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')


def model(constraints, objective=None):
    return dict(formulation='binary_ilp', variables=[0, 1], sense='max',
                objective=objective or [3, 5], constraints=constraints)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, required=True)
    output = parser.parse_args().output
    fixtures = output / 'synthetic-fixtures'
    fixtures.mkdir()
    constraints = dict(budget=None, min_count=None, max_count=None,
                       required=[], forbidden=[], implications=[])
    specifications = {
        'sA': constraints,
        'sB': dict(constraints, min_count=1),
        'sC': dict(constraints, required=[0], forbidden=[0]),
        'sD': dict(constraints, budget=1),
    }
    candidates = {'sA': model([]), 'sB': model([[[1, 1], '>=', 1]]),
                  'sC': model([[[1, 0], '==', 1], [[1, 0], '==', 0]]),
                  'sD': model([[[1, 2], '<=', 1]])}
    public = [dict(id=cid, language='fr' if cid in ('sA', 'sC') else 'en',
                   intention='SYNTHETIC SOFTWARE FIXTURE; not generated by an LLM.',
                   data=dict(n=2, weights=[3, 5], costs=[1, 2], edges=[]))
              for cid in specifications]
    labels = [dict(id=cid, constraints=value, families=['synthetic-software-fixture'])
              for cid, value in specifications.items()]
    write_json(fixtures / 'cases.json', public)
    write_json(fixtures / 'labels.json', labels)
    # Intentionally force validity precedence, score precedence, revision
    # fallback, format repair, mathematical repair and one guided regression.
    initial = {'sA': (candidates['sA'], -1), 'sB': ('not JSON', -.2),
               'sC': (candidates['sC'], -2), 'sD': (model([]), -.1)}
    direct = {'sA': (model([], [0, 0]), -.5), 'sB': (candidates['sB'], -9),
              'sC': ('not JSON', -.1), 'sD': (candidates['sD'], -.2)}
    self_phase = {'sA': ('not JSON', -.1), 'sB': (model([]), -.5),
                  'sC': (candidates['sC'], -4), 'sD': (candidates['sD'], -.5)}
    guided = {'sA': (model([], [6, 10]), -.5), 'sB': (candidates['sB'], -.5),
              'sC': ('not JSON', -.1), 'sD': (candidates['sD'], -.5)}
    phases = [('initial', initial), ('direct', direct), ('self', self_phase), ('guided', guided)]
    all_records = {}
    for phase_index, (phase, definitions) in enumerate(phases):
        records = []
        for cid, (candidate, probability) in definitions.items():
            text = candidate if isinstance(candidate, str) else json.dumps(candidate)
            tokens = 5 + phase_index
            records.append(dict(id=cid, phase=phase, raw_response=text, parsed=parse_model(text, 2),
                                mean_generated_log_probability=probability,
                                generated_token_ids=list(range(tokens)),
                                generated_token_log_probabilities=[probability] * tokens,
                                input_tokens=10 * (phase_index + 1), output_tokens=tokens,
                                wall_seconds=phase_index + 1, cpu_seconds=(phase_index + 1) / 10,
                                synthetic_software_fixture=True))
        all_records[phase] = records
        (fixtures / (phase + '.jsonl')).write_text(''.join(json.dumps(row) + '\n' for row in records))
    a = all_records['initial'][0]
    tie = copy.deepcopy(a)
    assert choose_direct(a, tie)[1] == 0
    assert choose_revision(a, all_records['self'][0])[1] == 0
    assert choose_revision(all_records['initial'][1], all_records['guided'][2])[1] == 1
    feedback(fixtures / 'cases.json', fixtures / 'labels.json', fixtures / 'initial.jsonl', output / 'feedback')
    minimal = json.loads((output / 'feedback/minimal.json').read_text())
    assert minimal['sB'] == {'kind': 'schema', 'message': SCHEMA_MESSAGE}
    assert minimal['sA']['kind'] == minimal['sC']['kind'] == 'no_counterexample'
    assert minimal['sD']['kind'] == 'counterexamples'
    for value in minimal.values():
        validate_feedback(value, 2)
        assert not set(value).intersection({'verification', 'constraints', 'objective', 'families', 'detail'})
    score(fixtures / 'cases.json', fixtures / 'labels.json', fixtures / 'initial.jsonl',
          fixtures / 'direct.jsonl', fixtures / 'self.jsonl', fixtures / 'guided.jsonl', output / 'scores')
    metrics = json.loads((output / 'scores/metrics.json').read_text())
    expected = {
        'initial': dict(schema_valid=3, faithful=2, optimization_equivalent=2, assignments_compared=12, feasibility_mismatches=2, objective_mismatches=0),
        'direct': dict(schema_valid=4, faithful=2, optimization_equivalent=2, repairs_to_faithful=1, format_repairs_to_faithful=1, mathematical_repairs_to_faithful=0, regressions_from_faithful=1, assignments_compared=16, feasibility_mismatches=2, objective_mismatches=3),
        'self': dict(schema_valid=4, faithful=3, optimization_equivalent=3, repairs_to_faithful=1, format_repairs_to_faithful=0, mathematical_repairs_to_faithful=1, regressions_from_faithful=0, assignments_compared=16, feasibility_mismatches=1, objective_mismatches=0),
        'guided': dict(schema_valid=4, faithful=3, optimization_equivalent=4, repairs_to_faithful=2, format_repairs_to_faithful=1, mathematical_repairs_to_faithful=1, regressions_from_faithful=1, assignments_compared=16, feasibility_mismatches=0, objective_mismatches=3),
    }
    for phase, counts in expected.items():
        got = metrics['methods'][phase]
        assert got['observed'] == 4
        assert got['portfolio_concordant'] == counts['schema_valid']
        assert got['usable_for_original_problem'] == counts['faithful']
        for field, value in counts.items():
            assert got[field] == value, (phase, field, got[field], value)
        for axis in ('language', 'reference_feasibility'):
            for field, value in got.items():
                assert sum(bucket[phase][field] for bucket in metrics['strata'][axis].values()) == value
        assert metrics['strata']['reference_feasibility']['infeasible'][phase]['observed'] == 1
        assert metrics['strata']['reference_feasibility']['infeasible'][phase]['faithful'] == 1
    assert metrics['physical_generation_calls'] == 16
    expected_physical = dict(input_tokens=400, output_tokens=104, wall_seconds=40, cpu_seconds=4)
    for field, value in expected_physical.items():
        assert math.isclose(metrics['physical_generation_cost'][field], value)
    for phase, inputs, outputs, wall in [('direct', 120, 44, 12), ('self', 160, 48, 16), ('guided', 200, 52, 20)]:
        got = metrics['attributable_cost_per_arm'][phase]
        assert got['input_tokens'] == inputs and got['output_tokens'] == outputs and got['wall_seconds'] == wall
    assert metrics['H15']['status'] == 'not_supported_in_finite_test'
    assert metrics['H15']['guided_minus_self_faithful'] == 0
    assert metrics['H15']['guided_regressions'] == 1
    score(fixtures / 'cases.json', fixtures / 'labels.json', fixtures / 'initial.jsonl',
          None, None, None, output / 'development-initial-only')
    dev = json.loads((output / 'development-initial-only/metrics.json').read_text())
    assert dev['H15'] == {'status': 'development_only'}
    assert set(dev['methods']) == {'initial'} and dev['physical_generation_calls'] == 4
    write_json(output / 'raw.json', dict(
        status='software_checks_passed',
        evidence_kind='SYNTHETIC SOFTWARE FIXTURES; NO LLM PERFORMANCE',
        expected_counts=expected, expected_physical_fixture_cost=expected_physical,
        observed_metrics=metrics, minimal_feedback=minimal,
        selector_controls=3, fixture_count=4,
        scope='Offline selection, feedback and metric bookkeeping only; no real test generation or H15 inference.'))
    print('Synthetic software fixture audit passed; no LLM performance inferred.')


if __name__ == '__main__':
    main()
